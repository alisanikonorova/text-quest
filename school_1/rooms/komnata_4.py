# rooms/komnata_4.py
from assets.images import HIDE_AND_KNIFE, KNIFE, BONES
from inventory import has_item, get_items

def komnata_4() -> str:
    print("\n" + "="*50)
    print("Вы вошли в последнюю комнату. Здесь большое окно, ведущее на улицу.")
    print("Вдруг вы слышите тяжёлые шаги за спиной... Кто-то приближается!")
    print(f"Ваш инвентарь: {get_items()}")
    choice = input("1 - закричать, 2 - прыгнуть в окно, 3 - спрятаться и достать нож: ")

    if choice == "1":
        print("Вы закричали изо всех сил...")
        print("Шаги ускорились. Дверь распахнулась. Вас настигла мучительная смерть.")
        print("КОНЕЦ. ВЫ ПОГИБЛИ.")
        return "end"

    elif choice == "2":
        if has_item("верёвка"):
            print("Вы привязали верёвку к раме и спокойно спустились вниз.")
            print("Вы на свободе! Вы спаслись!")
            print("КОНЕЦ. ПОБЕДА!")
        else:
            print("Вы прыгнули из окна второго этажа без страховки...")
            print("Вы сломали ноги, но остались живы. Вас нашли прохожие.")
            print("КОНЕЦ. ВЫ ЖИВЫ, НО ИЗУВЕЧЕНЫ.")
        return "end"

    elif choice == "3":
        if has_item("нож"):
            print("Вы спрятались в тени с ножом наготове.")
            print(HIDE_AND_KNIFE)
            print("Вошёл вооружённый человек — вы нанесли удар и обезвредили его!")
            print(KNIFE)
            print("Вы выбрались через окно на улицу.")
            print("КОНЕЦ. ГЕРОИЧЕСКАЯ ПОБЕДА!")
        else:
            print("У вас нет ножа! Вы не смогли спрятаться и обезвредить врага.")
            print("Вас настигла мучительная смерть.")
            print("КОНЕЦ. ВЫ ПОГИБЛИ. А ЛЮДИ НАШЛИ ТВОИ КОСТИ.")
            print(BONES)
        return "end"

    else:
        print("Неверный ввод. Введите 1, 2 или 3.")
        return "komnata_4"